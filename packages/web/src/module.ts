import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { existsSync, readdirSync, readFileSync } from 'node:fs'
import { addTemplate, defineNuxtModule, updateTemplates } from '@nuxt/kit'
import type { BlockDef, ThemeDef } from '@sirilcms/contracts'

export type SirilModuleOptions = { blocks?: BlockDef[]; themes?: ThemeDef[] }

export default defineNuxtModule<SirilModuleOptions>({
  meta: { name: 'siril-web', configKey: 'siril' },
  defaults: { blocks: [], themes: [] },
  setup(options, nuxt) {
    const runtimeDir = fileURLToPath(new URL('./runtime', import.meta.url))
    // `_layers` is typed `readonly NuxtConfigLayer[]` — reassign (append module layer last so the app layer keeps precedence, per S0.1)
    nuxt.options._layers = [
      ...nuxt.options._layers,
      {
        config: {
          rootDir: runtimeDir,
          srcDir: join(runtimeDir, 'app'),
          // kit getLayerDirectories resolves layer server as resolve(srcDir, serverDir || 'server');
          // runtime/server sits beside runtime/app (not under it), so it must be set explicitly
          serverDir: join(runtimeDir, 'server'),
        },
        cwd: runtimeDir,
        configFile: '',
      },
    ]
    nuxt.options.alias['#siril'] = runtimeDir
    // Расширения проекта (siril.blocks / siril.themes) → данные для registerExtensions. Плагины
    // runtime/app/plugins/00.siril-registry.ts (SSR+клиент) и runtime/server/plugins/00.siril-registry.ts (Nitro)
    // подхватываются слоем модуля и вызывают registerExtensions до любого рендера.
    const registry = addTemplate({
      // .ts (не .mjs): path-алиас tsconfig указывает на файл без расширения. Содержимое — чистый JS (без TS-синтаксиса):
      // Nitro не транспилирует .ts из node_modules/.cache. Тип сужается кастом в плагинах.
      filename: 'siril/registry.gen.ts',
      write: true,
      getContents: () => registryContents(options),
    })
    nuxt.options.alias['#siril-registry'] = registry.dst
    type NitroCfg = { alias?: Record<string, string> }
    ;(nuxt.hook as unknown as (name: string, cb: (cfg: NitroCfg) => void) => void)('nitro:config', (cfg) => {
      cfg.alias = { ...cfg.alias, '#siril-registry': registry.dst }
    })
    addTemplate({
      filename: 'siril/theme-styles.gen.mjs',
      write: true,
      getContents: () => themeStylesContents(runtimeDir, nuxt.options.rootDir),
    })
    addTemplate({
      filename: 'siril/block-registry.gen.mjs',
      write: true,
      getContents: () => blockRegistryContents(runtimeDir, nuxt.options.srcDir),
    })
    // Проектные блоки/темы сканируются fs'ом (не import.meta.glob: из виртуального модуля .nuxt/siril glob
    // резолвится относительно vite-root и в Nuxt 4 не находит файлы проекта). Новые/удалённые файлы — пересборка шаблонов.
    nuxt.hook('builder:watch', async (_event, relPath) => {
      const p = String(relPath).split('\\').join('/')
      if (/(^|\/)(blocks\/[^/]+\/[^/]+\.vue|themes\/[^/]+\/tokens\.css)$/.test(p)) {
        await updateTemplates({ filter: (t) => t.filename.startsWith('siril/') })
      }
    })
  },
})

export function registryContents(options: SirilModuleOptions): string {
  return `// Generated by @sirilcms/web — project extensions (siril.blocks / siril.themes). Do not edit.
export default ${JSON.stringify({ blocks: options.blocks ?? [], themes: options.themes ?? [] })}
`
}

export function themeStylesContents(runtimeDir: string, projectRootDir?: string): string {
  const moduleThemes: Record<string, string> = {}
  const themesDir = join(runtimeDir, 'themes')
  if (existsSync(themesDir)) {
    for (const entry of readdirSync(themesDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const css = join(themesDir, entry.name, 'tokens.css')
      if (existsSync(css)) moduleThemes[entry.name] = readFileSync(css, 'utf-8')
    }
  }
  return [
    '// moduleThemes is fs-embedded from the module runtime dir; projectThemes is fs-scanned from <rootDir>/themes (absolute ?raw imports; project > module precedence is a layout concern)',
    `export const moduleThemes = ${JSON.stringify(moduleThemes)}`,
    `export const projectThemes = ${projectThemesMap(projectRootDir)}`,
    '',
  ].join('\n')
}

export function blockRegistryContents(runtimeDir: string, projectSrcDir?: string): string {
  const placeholder = join(runtimeDir, 'app', 'blocks', 'Placeholder.vue').split('\\').join('/')
  const blocksDir = join(runtimeDir, 'app', 'blocks')
  // module runtime lives outside the app root — globs cannot reach it (S0.1: only root-relative
  // globs work from a generated virtual module), so module blocks are fs-embedded here as
  // absolute-path dynamic imports (walk <type>-dirs; Placeholder.vue at the blocks root is not a block type)
  const moduleBlocks: string[] = []
  if (existsSync(blocksDir)) {
    for (const type of readdirSync(blocksDir, { withFileTypes: true })) {
      if (!type.isDirectory()) continue
      const typeDir = join(blocksDir, type.name)
      for (const file of readdirSync(typeDir, { withFileTypes: true })) {
        if (!file.isFile() || !file.name.endsWith('.vue')) continue
        const abs = join(typeDir, file.name).split('\\').join('/')
        moduleBlocks.push(`  ${JSON.stringify(`${type.name}/${file.name}`)}: () => import(${JSON.stringify(abs)}),`)
      }
    }
  }
  const moduleMap = moduleBlocks.length ? `{\n${moduleBlocks.join('\n')}\n}` : '{}'
  const merged = [
    '// Generated by @sirilcms/web (module.ts addTemplate) — do not edit.',
    '// Dual-source block registry: moduleBlocks (fs-embedded from the module runtime, absolute-path imports)',
    '// + projectBlocks (fs-scanned <srcDir>/blocks/<type>/<Variant>.vue as absolute imports; import.meta.glob from a',
    '// generated module resolves against the vite root and finds nothing in Nuxt 4). Key shape for both: <type>/<Variant>.vue; project wins on conflict.',
    "import { defineAsyncComponent } from 'vue'",
    `import Placeholder from '${placeholder}'`,
    '',
    'const pascal = (s) => s.charAt(0).toUpperCase() + s.slice(1)',
    '',
    `const moduleBlocks = ${moduleMap}`,
    '',
    `const projectBlocks = ${projectBlocksMap(projectSrcDir)}`,
    '// glob keys are root-relative with the leading "/" dropped (S0.1: /themes/... -> "themes/...")',
    "const rekeyProject = (k) => k.replace(/^\\/?app\\/blocks\\//, '')",
    '// filter project entries by rekey result: must be <type>/<Variant>.vue — drop Placeholder.vue (a fallback, not a block type)',
    '// and bare files picked up directly under app/blocks (rekey result without "/" is not a block key)',
    "const isBlockKey = (k) => k !== 'Placeholder.vue' && k.includes('/')",
    'const merged = {',
    '  ...moduleBlocks,',
    '  ...Object.fromEntries(Object.entries(projectBlocks).filter(([path]) => isBlockKey(rekeyProject(path))).map(([path, loader]) => [rekeyProject(path), loader])),',
    '}',
    '',
    'export function getBlockComponent(type, variant) {',
    '  const loader = merged[`${type}/${pascal(variant)}.vue`]',
    '  if (!loader) return Placeholder',
    '  return defineAsyncComponent(loader)',
    '}',
    '',
  ]
  return merged.join('\n')
}

const posix = (p: string) => p.split('\\').join('/')

/** Проектные блоки: ключ `app/blocks/<type>/<Variant>.vue` (как раньше давал glob) → absolute dynamic import. */
export function projectBlocksMap(srcDir?: string): string {
  const entries: string[] = []
  const blocksDir = srcDir ? join(srcDir, 'blocks') : ''
  if (blocksDir && existsSync(blocksDir)) {
    for (const type of readdirSync(blocksDir, { withFileTypes: true })) {
      if (!type.isDirectory()) continue
      for (const file of readdirSync(join(blocksDir, type.name), { withFileTypes: true })) {
        if (!file.isFile() || !file.name.endsWith('.vue')) continue
        const abs = posix(join(blocksDir, type.name, file.name))
        entries.push(`  ${JSON.stringify(`app/blocks/${type.name}/${file.name}`)}: () => import(${JSON.stringify(abs)}),`)
      }
    }
  }
  return entries.length ? `{\n${entries.join('\n')}\n}` : '{}'
}

/** Проектные темы: ключ `/themes/<id>/tokens.css` → загрузчик ?raw (формат, который ждёт layouts/default.vue). */
export function projectThemesMap(rootDir?: string): string {
  const entries: string[] = []
  const themesDir = rootDir ? join(rootDir, 'themes') : ''
  if (themesDir && existsSync(themesDir)) {
    for (const entry of readdirSync(themesDir, { withFileTypes: true })) {
      if (!entry.isDirectory()) continue
      const css = join(themesDir, entry.name, 'tokens.css')
      if (!existsSync(css)) continue
      entries.push(`  ${JSON.stringify(`/themes/${entry.name}/tokens.css`)}: () => import(${JSON.stringify(`${posix(css)}?raw`)}).then((m) => m.default),`)
    }
  }
  return entries.length ? `{\n${entries.join('\n')}\n}` : '{}'
}
